            "fe-architect-scaffold",
            "fe-feature-architect-discover", "fe-feature-architect-from-prototype",
            "fe-feature-architect-spec-delta", "fe-feature-architect-backlog",
            "fe-feature-architect-scaffold",
            "fe-validator", "fe-planner", "fe-implement", "fe-autopilot",
            "next-phase",
