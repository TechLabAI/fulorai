def _render_checklist(ctx: dict[str, Any]) -> str:
    """Render project-checklist.md from the context (D-295).

    Produces the ETAPA 1 setup-phase sections (one `### P<n> — ...` per
    setup.phase so `checklist.py sync` can flip them to done) and the ETAPA 2
    'Módulos backend' anchor that `checklist.py add-module` appends under.
    Human-facing doc → pt-BR (R6).
    """
    display = ctx.get("project", {}).get("displayName", "Project")
    phases = ctx.get("setup", {}).get("phases", [])
    out = [f"# {display} — Checklist", "",
           "> Progresso do projeto. Setup (ETAPA 1) é sincronizado de "
           "`project-context.json` via `scripts/checklist.py sync`.", "",
           "## ETAPA 1 — Setup", ""]
    for ph in phases:
        pid = ph.get("id", "")
        prefix = pid.split("-", 1)[0]
        name = ph.get("name", pid)
        cond = ph.get("conditional")
        suffix = f"  _(condicional: {cond})_" if cond else ""
        out.append(f"### {prefix} — {name}{suffix}")
        cmd = ph.get("command")
        out.append(f"- [ ] {name}" + (f" (`{cmd}`)" if cmd else ""))
        out.append("")
    out += ["## ETAPA 2 — Desenvolvimento", "",
            "### Módulos backend", ""]
    registry = ctx.get("modules", {}).get("registry", [])
    if registry:
        for m in registry:
            pfx = (m.get("prefix") or "MOD").upper()
            disp = m.get("displayName", pfx)
            svc = m.get("backendService") or f"{pfx.lower()}-service"
            out.append(f"#### {pfx} — {disp} (`{svc}`)")
            out.append(f"- [ ] **Arquitetura** — `/be-architect-vision {pfx}` → "
                       f"specs → backlog → scaffold")
            out.append(f"- [ ] **Ciclo de desenvolvimento** — "
                       f"`/be-validator {pfx}` → planner → implement")
            out.append("- **Status atual:** declared")
            out.append("")
    else:
        out.append("_Nenhum módulo de negócio registrado ainda. "
                   "Use `/register-module` ou `checklist.py add-module`._")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def _seed_operational_state(
    workspace: Path, target: Path, ctx: dict[str, Any]
) -> None:
    """Guarantee the operational scaffolding every generated project relies on.

    D-295: the discovery (D-073) and `--context` intake paths can produce a
    context WITHOUT the `setup` block, leaving the project's own commands
    (`/next-phase`, `context.py mark-phase`/`summary`, `checklist.py`) and the
    journal non-functional. This seeds, idempotently and regardless of context
    source:
      1. `setup.phases` — copied from the canonical context template, all reset
         to `pending` (mark_phase then flips each as phases run);
      2. `project-journal.md` — title + usage note (journal.py requires the
         file to pre-exist);
      3. `project-checklist.md` — ETAPA 1 phase sections + ETAPA 2 anchor.
    """
    changed = False
    if not ctx.get("setup", {}).get("phases"):
        tmpl_path = (workspace / "templates" / "operational" / "root"
                     / "project-context.template.json")
        phases: list[dict[str, Any]] = []
        try:
            tmpl = json.loads(tmpl_path.read_text(encoding="utf-8"))
            # Deep copy via round-trip (avoids a stdlib import just for this).
            phases = json.loads(json.dumps(tmpl.get("setup", {}).get("phases", [])))
        except (OSError, json.JSONDecodeError) as e:
            print(f"warning: could not seed setup.phases from template: {e}",
                  file=sys.stderr)
        for ph in phases:
            ph["status"] = "pending"
            for k in ("startedAt", "completedAt", "$comment_status"):
                ph.pop(k, None)
        ctx["setup"] = {"phases": phases}
        changed = True
    if changed:
        save_context(target, ctx)

    journal = target / "project-journal.md"
    if not journal.exists():
        display = ctx.get("project", {}).get("displayName", "Project")
        journal.write_text(
            f"# {display} — Project Journal\n\n"
            "> Append-only activity log (D-011). Append with "
            "`scripts/journal.py append`.\n"
            "> Never edit past entries; corrections are new `[CORRECTION]` "
            "entries referencing the original timestamp.\n",
            encoding="utf-8")

    checklist = target / "project-checklist.md"
    if not checklist.exists():
        checklist.write_text(_render_checklist(ctx), encoding="utf-8")


def cmd_bootstrap(args: argparse.Namespace) -> int:
    """P0 — Create target directory, git init, .gitignore, README.md, tmp/.

    D-073: optional `--discovery <path>` runs a Pre-0 ingestion pass that
    extracts project-context.json from Business Analysis output (LBC,
    technical-framing, ADRs, glossary, wireframe). Unresolved fields are
    surfaced in `<target>/_inbox/UNRESOLVED_QUESTIONS.md`; original ADRs are
    copied verbatim to `<target>/_inbox/adr/` as discovery history.
    """
    target = args.target.resolve()
    workspace = find_workspace_root(args.workspace)
    ctx_override = args.context
    discovery_path = getattr(args, "discovery", None)

    # D-278: validate manifest BEFORE any write so a bad archetype never leaves
    # a half-created target. At this point context may not exist yet, so we use
    # the --archetype flag only (context read happens below).
    _pre_archetype = getattr(args, "archetype", None) or "code-monorepo"
    _manifest = load_segment_manifest(workspace, _pre_archetype)
    validate_manifest(_manifest, workspace)

    if target.exists() and any(target.iterdir()):
        if not args.force:
            sys.exit(f"error: target {target} exists and is not empty (use --force to overwrite)")

    target.mkdir(parents=True, exist_ok=True)
    print(f"[P0] target: {target}")

    # ── Pre-0: Discovery ingestion (D-073) ──────────────────────────────────
    if discovery_path:
        if ctx_override:
            sys.exit("error: --discovery and --context are mutually exclusive "
                     "(discovery PRODUCES the context; context PROVIDES it).")
        from ingest_discovery import (
            ingest_discovery, render_unresolved_questions_md,
        )
        print(f"[Pre-0] ingesting discovery from: {discovery_path}")
        try:
            result = ingest_discovery(discovery_path.resolve())
        except FileNotFoundError as e:
            sys.exit(f"error: {e}")
        ctx_data = result.context
        save_context(target, ctx_data)
        # Copy ADRs verbatim to _inbox/adr/ (D-073: stay there permanently).
        inbox_adr = target / "_inbox" / "adr"
        inbox_adr.mkdir(parents=True, exist_ok=True)
        for adr_src in result.adr_files:
            (inbox_adr / adr_src.name).write_bytes(adr_src.read_bytes())
        # D-074: write aspect overrides derived from discovery to
        # <target>/arch/overrides/<aspect>.partial.json. P2 deep-merges these
        # onto the workspace defaults before pinning the snapshot.
        n_overrides = 0
        if result.aspect_overrides:
            overrides_dir = target / "arch" / "overrides"
            overrides_dir.mkdir(parents=True, exist_ok=True)
            for aspect_name, partial in result.aspect_overrides.items():
                out_path = overrides_dir / f"{aspect_name}.partial.json"
                out_path.write_text(
                    json.dumps(partial, indent=2, ensure_ascii=False) + "\n",
                    encoding="utf-8",
                )
                n_overrides += 1
        # UNRESOLVED_QUESTIONS.md for the human to address before P1.
        questions_md = render_unresolved_questions_md(
            result, discovery_path.resolve())
        (target / "_inbox" / "UNRESOLVED_QUESTIONS.md").write_text(
            questions_md, encoding="utf-8")
        print(f"[Pre-0] ingested {len(result.sources)} field(s), "
              f"{len(result.unresolved)} unresolved, "
              f"{len(result.adr_files)} ADR(s), "
              f"{n_overrides} aspect override(s) written")
        if result.unresolved:
            print(f"[Pre-0] NEXT: fill in {len(result.unresolved)} items in "
                  f"{target / '_inbox' / 'UNRESOLVED_QUESTIONS.md'} "
                  f"+ edit {target / 'project-context.json'} before running P1.")
    # If --context was passed, copy the context file into the target.
    elif ctx_override:
        ctx_data = json.loads(ctx_override.read_text(encoding="utf-8"))
        save_context(target, ctx_data)
    else:
        # Expect project-context.json already present at target.
        if not (target / "project-context.json").exists():
            sys.exit("error: project-context.json not found at target, and "
                     "neither --context nor --discovery was provided")
        ctx_data = load_context(target, None)

    # D-280/D-281: reconcile archetype (flag > context > default) and persist.
    # Deep-merge context_defaults from the manifest first (manifest defaults yield
    # to any user-specified values already in ctx_data). Then set project.archetype
    # explicitly so it's always present regardless of manifest content.
    archetype = resolve_archetype(args, ctx_data)
    ctx_defaults = _manifest.get("context_defaults", {})
    if ctx_defaults:
        ctx_data = _deep_merge(ctx_defaults, ctx_data)
    ctx_data.setdefault("project", {})["archetype"] = archetype
    save_context(target, ctx_data)
    print(f"[P0] archetype: {archetype} (phases: {' -> '.join(resolve_phase_set(_manifest))})")

    # D-278 Fase C: copy segment seeds verbatim into the project (R2-normalized).
    seed_count = _apply_seeds(workspace, _manifest, target)
    if seed_count:
        print(f"[P0] seeds: {seed_count} file(s) copied from {_manifest.get('name', archetype)!r} segment")

    # D-295: seed operational scaffolding (setup.phases + journal + checklist)
    # so discovery/--context-produced contexts get a project that its own
    # commands (mark-phase, summary, /next-phase, checklist.py) can drive.
    _seed_operational_state(workspace, target, ctx_data)

    project_name = ctx_data["project"]["name"]
    project_display = ctx_data["project"]["displayName"]

    # .gitignore — minimal, depends on stack
    has_frontend = ctx_data["stack"]["frontend"]["enabled"]
    gitignore_lines = [
        "# Build artifacts",
        "build/",
        "out/",
        ".gradle/",
        "target/",
        "",
        "# IDE",
        ".idea/",
        "*.iml",
        ".vscode/",
        "",
        "# OS",
        ".DS_Store",
        "Thumbs.db",
        "",
        "# Secrets",
        ".env",
        ".env.local",
        "",
        "# Python (for scripts/)",
        "__pycache__/",
        "*.pyc",
        ".venv/",
        "",
    ]
    if has_frontend:
        gitignore_lines += [
            "# Frontend",
            "node_modules/",
            "dist/",
            ".nx/",
            "",
        ]
    # Note: tmp/ root is intentionally NOT in .gitignore (D-041 — used for project state).
    # F-CKPT (D-326): autopilot checkpoint directories are ephemeral and must be gitignored.
    gitignore_lines += [
        "# Autopilot checkpoints (ephemeral runtime state — F-CKPT, D-326)",
        "tmp/be-architecture-autopilot/",
        "tmp/fe-architecture-autopilot/",
        "",
    ]
    (target / ".gitignore").write_text("\n".join(gitignore_lines), encoding="utf-8")

    # README.md — minimal, will be expanded in P1 via CLAUDE.md template
    readme = (
        f"# {project_display}\n\n"
        f"{ctx_data['project']['description']}\n\n"
        f"## Getting started\n\n"
        f"This project was bootstrapped by `techlab-architecture /new-project`.\n\n"
        f"- See `CLAUDE.md` for the full project guide (architecture, modules, conventions).\n"
        f"- See `project-checklist.md` for the development progress.\n"
        f"- Run `/next-phase` to navigate the current state.\n"
    )
    (target / "README.md").write_text(readme, encoding="utf-8")

    # tmp/ — versioned per D-041
    tmp_dir = target / "tmp"
    tmp_dir.mkdir(exist_ok=True)
    (tmp_dir / "README.md").write_text(
        "# tmp/\n\n"
        "Checkpoint storage for autopilot (`tmp/be-autopilot/<ID>/state.json`).\n\n"
        "**This directory is versioned** (decision D-041) — checkpoints travel with the project.\n",
        encoding="utf-8",
    )

    # git init
    if not (target / ".git").exists():
        try:
            subprocess.run(
                ["git", "init", "--quiet", "--initial-branch=main"],
                cwd=target,
                check=True,
            )
        except (subprocess.CalledProcessError, FileNotFoundError) as e:
            print(f"warning: git init failed: {e}", file=sys.stderr)

    mark_phase(target, ctx_data, "P0-bootstrap", "done")
    print(f"[P0] done — {target}/.gitignore, README.md, tmp/, .git/")

    # D-098: auto-register the project in the workspace's clients/ registry
    # so impact_analysis.py can find it without a manual JSON edit. Runs after
    # P0 finishes so any failure above aborts before touching the registry.
    register_as = getattr(args, "register_as", None)
    if register_as:
        registered = register_client(
            workspace, target, register_as, ctx_data,
            force=bool(getattr(args, "force", False)),
        )
        print(f"[register] {registered.relative_to(workspace).as_posix()}")
    return 0


