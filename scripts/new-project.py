def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="new-project.py",
        description=(
            "Materialize project bootstrap phases (P0, P1, P2, P4, P5, Pk, Pe). "
            "Archetype flag selects which phases run (D-278..D-281)."
        ),
    )
    parser.add_argument(
        "--workspace",
        type=Path,
        default=None,
        help="Path to techlab-architecture workspace (default: $TECHLAB_ARCH_HOME or walk up)",
    )

    sub = parser.add_subparsers(dest="phase", required=True)

    def add_common(p: argparse.ArgumentParser) -> None:
        p.add_argument("--target", type=Path, required=True, help="Path to the new project root")
        p.add_argument(
            "--context",
            type=Path,
            default=None,
            help="Path to project-context.json (default: <target>/project-context.json)",
        )

    def add_archetype(p: argparse.ArgumentParser) -> None:
        p.add_argument(
            "--archetype",
            default=None,
            metavar="NAME",
            help=(
                "Project shape: code-monorepo (default) | knowledge-lab. "
                "Precedence: flag > context.project.archetype > code-monorepo (D-280)."
            ),
        )

    p0 = sub.add_parser("bootstrap", help="P0 — initial skeleton + git init")
    add_common(p0)
    add_archetype(p0)
    p0.add_argument("--force", action="store_true",
                    help="Overwrite non-empty target (also overwrites an existing client registry entry).")
    p0.add_argument(
        "--discovery",
        type=Path,
        default=None,
        help=("Pre-0 ingestion: path to a discovery directory "
              "(business/ + architecture/adr/ + optional design/). "
              "Generates project-context.json + _inbox/UNRESOLVED_QUESTIONS.md "
              "before P0 proceeds. Mutually exclusive with --context. D-073."),
    )
    p0.add_argument(
        "--register-as",
        metavar="CLIENT_ID",
        default=None,
        help=("D-098: after P0 finishes, write <workspace>/clients/<CLIENT_ID>.json "
              "so scripts/impact_analysis.py can discover this project. "
              "CLIENT_ID must be kebab-case (lowercase, starts with alnum, "
              "hyphens allowed). Skipped when omitted."),
    )
    p0.set_defaults(func=cmd_bootstrap)

    p1 = sub.add_parser("claude-folder", help="P1 — .claude/ + CLAUDE.md")
    add_common(p1)
    add_archetype(p1)
    p1.add_argument(
        "--exclude-architect-commands",
        action="store_true",
        help=("(D-296) Opt OUT of shipping architect-level commands "
              "(be-architect-*, fe-architect-*, fe-feature-architect-*) — "
              "produces a lean dev-only project (validator/planner/implement/"
              "autopilot only). By default architect commands ARE shipped, "
              "since LAYER 1 runs inside the generated project."),
    )
    p1.add_argument(
        "--include-architect-commands",
        action="store_true",
        help="(deprecated, no-op) Architect commands now ship by default (D-296).",
    )
    p1.set_defaults(func=cmd_claude_folder)

    p2 = sub.add_parser("docs-skeleton", help="P2 — docs/architecture/ tree")
    add_common(p2)
    add_archetype(p2)
    p2.add_argument(
        "--rigor",
        choices=list(DOCS_SKELETON.keys()),
        default=None,
        help="Override rigor (default: read from project-context.json)",
    )
    p2.add_argument(
        "--with-code-mapping",
        action="store_true",
        help=("Pin templates/architecture/shared/code-mapping/code-mapping.arch.json "
              "(+ schema, README) into <target>/arch/shared/code-mapping/. Read-only "
              "aspect consumed by scripts/be-spec-drift.py. Opt-in: PP v2 S5 default off "
              "(D-160, D-161)."),
    )
