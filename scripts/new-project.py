def shared_lib_specs(term: str) -> list[tuple[str, str, str]]:
    """D-328 (FE-4): the 9 foundational shared libs (Wave-0) + typecheck-clean stubs.

    Each tuple is (name, type-tag, stub TS). These libs must EXIST before any module
    is scaffolded (module-pattern pre-condition) so `@<scope>/shared/*` imports resolve.
    `<term>-context` is parameterized by the project's multi-tenancy term.
    """
    term_cap = term[:1].upper() + term[1:]
    return [
        ("auth-session", "data-access", "export interface AuthSession { readonly token: string | null; }\n"),
        (f"{term}-context", "domain", f"export interface {term_cap}Context {{ readonly id: string | null; }}\n"),
        ("access-decision", "domain", "export interface AccessDecision { can(permission: string): boolean; }\n"),
        ("access-http-base", "data-access", "export const ACCESS_HTTP_BASE = '/api';\n"),
        ("error-model", "domain", "export interface AppError { readonly code: string; readonly message: string; }\n"),
        ("observability", "data-access", "export interface Telemetry { event(name: string): void; }\n"),
        ("ui-tokens", "ui", "export const UI_TOKENS_VERSION = '0.0.0';\n"),
        ("ui-components", "ui", "export const UI_COMPONENTS_VERSION = '0.0.0';\n"),
        ("ui-feedback", "ui", "export const UI_FEEDBACK_VERSION = '0.0.0';\n"),
    ]


def scaffold_shared_libs(libs_dir: Path, npm_scope: str, term: str) -> list[str]:
    """Emit the foundational shared libs (D-328) under libs/shared/<name>/ with a
    project.json (tags type:*/scope:shared), a barrel index.ts and a stub. Returns
    the list of names scaffolded. Unlike module libs (D-331), shared libs are not
    spec-driven — they are foundational, so pre-creating their src is correct."""
    names: list[str] = []
    for name, tag, stub in shared_lib_specs(term):
        lib_dir = libs_dir / "shared" / name
        (lib_dir / "src" / "lib").mkdir(parents=True, exist_ok=True)
        (lib_dir / "project.json").write_text(
            json.dumps({
                "name": f"shared-{name}",
                "projectType": "library",
                "sourceRoot": f"libs/shared/{name}/src",
                "tags": [f"type:{tag}", "scope:shared"],
            }, indent=2) + "\n",
            encoding="utf-8",
        )
        (lib_dir / "src" / "index.ts").write_text(
            f"export * from './lib/{name}';\n", encoding="utf-8")
        (lib_dir / "src" / "lib" / f"{name}.ts").write_text(
            f"// @{npm_scope}/shared/{name} — Wave-0 stub (D-328/FE-4); "
            f"flesh out in the implement cycle.\n{stub}",
            encoding="utf-8",
        )
        names.append(name)
    return names


