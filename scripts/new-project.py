    jinja_ctx = build_jinja_context(ctx_data)
    jinja_ctx["angular_version"] = angular_version
    jinja_ctx["nx_version"] = nx_version

    # D-082: pre-populate libs/ + tsconfig paths from project-context.modules.registry.
    # Respect `hasUi` (skip backend-only / infra modules) and `frontendLib`
    # (strip leading "libs/" if present); fall back to lowercased prefix.
    modules = (ctx_data.get("modules") or {}).get("registry") or []
    lib_names: list[str] = []
    for m in modules:
        if m.get("hasUi") is False:
            continue
        if m.get("isInfrastructure") is True:
            continue
        prefix = (m.get("prefix") or "").lower()
        lib_field = m.get("frontendLib")
        if lib_field:
            lib = lib_field[len("libs/"):] if lib_field.startswith("libs/") else lib_field
        else:
            lib = prefix
        if not lib:
            continue
        lib_names.append(lib)

    # D-289: nx.json — render from template; fallback to minimal stub if template absent.
    if not render_jinja(workspace, "operational/infra/frontend-nx.json.j2", jinja_ctx,
                        frontend_dir / "nx.json"):
        nx_json = {
            "version": 3,
            "namedInputs": {
                "default": ["{projectRoot}/**/*", "sharedGlobals"],
                "production": ["default"],
                "sharedGlobals": [],
            },
            "$schema": "./node_modules/nx/schemas/nx-schema.json",
            "targetDefaults": {
                "build": {"cache": True},
                "test": {"cache": True},
                "lint": {"cache": True},
            },
        }
        (frontend_dir / "nx.json").write_text(json.dumps(nx_json, indent=2), encoding="utf-8")

    # D-328 (FE-4): foundational shared libs term (parameterized by multi-tenancy term).
    shared_term = (ctx_data.get("multiTenancy") or {}).get("term", "tenant")

    # tsconfig.base.json — paths pre-populated per D-082 from modules.registry + shared libs.
    tsconfig_paths: dict[str, list[str]] = {
        f"@{npm_scope}/{lib}": [f"libs/{lib}/src/index.ts"] for lib in lib_names
    }
    tsconfig_paths.update({
        f"@{npm_scope}/shared/{name}": [f"libs/shared/{name}/src/index.ts"]
        for name, _, _ in shared_lib_specs(shared_term)
    })
    tsconfig_base = {
        "compileOnSave": False,
        "compilerOptions": {
            "rootDir": ".",
            "sourceMap": True,
            "declaration": False,
            "moduleResolution": "node",
            "emitDecoratorMetadata": True,
            "experimentalDecorators": True,
            "importHelpers": True,
            "target": "ES2022",
            "module": "ES2022",
            "lib": ["ES2022", "dom"],
            "skipLibCheck": True,
            "skipDefaultLibCheck": True,
            "baseUrl": ".",
            "paths": tsconfig_paths,
        },
        "_TODO_lote_6a": "extend paths as additional libs (feature/data-access/ui) are scaffolded",
    }
    (frontend_dir / "tsconfig.base.json").write_text(
        json.dumps(tsconfig_base, indent=2), encoding="utf-8"
    )

    # D-289: package.json — render from template; fallback to minimal stub if template absent.
    if not render_jinja(workspace, "operational/infra/frontend-package.json.j2", jinja_ctx,
                        frontend_dir / "package.json"):
        package_json = {
            "name": f"{project_name}-frontend",
            "version": "0.1.0",
            "private": True,
            "dependencies": {},
            "devDependencies": {
                "@angular/core": f"^{angular_version}.0.0",
                "@angular/cli": f"^{angular_version}.0.0",
                "@nx/angular": f"^{nx_version}.0.0",
                "nx": f"^{nx_version}.0.0",
                "typescript": "~5.4.0",
            },
        }
        (frontend_dir / "package.json").write_text(
            json.dumps(package_json, indent=2), encoding="utf-8"
        )

    # apps/<name>-web/ — Angular shell stub
    app_dir = frontend_dir / "apps" / f"{project_name}-web"
    app_dir.mkdir(parents=True, exist_ok=True)
    (app_dir / "README.md").write_text(
        f"<!-- TODO[lote-6a]: scaffold via Nx generator with full Angular shell -->\n\n"
        f"# {project_name}-web\n\n"
        f"Angular shell application. To scaffold properly run "
        f"`npx nx generate @nx/angular:app {project_name}-web` after `npm install`.\n",
        encoding="utf-8",
    )

    # libs/ — pre-populated per D-082 from modules.registry.
    libs_dir = frontend_dir / "libs"
    libs_dir.mkdir(exist_ok=True)
    if lib_names:
        for lib in lib_names:
            lib_root = libs_dir / lib
            lib_root.mkdir(exist_ok=True)
            (lib_root / ".gitkeep").touch()
            (lib_root / "README.md").write_text(
                f"<!-- TODO[lote-6a]: scaffold via `npx nx generate @nx/angular:lib {lib}` -->\n\n"
                f"# @{npm_scope}/{lib}\n\n"
                f"Library placeholder for module `{lib}`. The folder structure will be\n"
                f"completed by the Nx generator after `npm install`.\n",
                encoding="utf-8",
            )
    else:
        (libs_dir / ".gitkeep").touch()

    # D-328 (FE-4): scaffold the foundational shared libs (Wave-0) with typecheck-clean stubs.
    shared_scaffolded = scaffold_shared_libs(libs_dir, npm_scope, shared_term)
    print(f"[P5] shared libs scaffolded: {len(shared_scaffolded)} "
          f"({', '.join(shared_scaffolded)})")

    # D-289: render Angular app shell templates into apps/{project_name}-web/src/app/.
    app_src_dir = app_dir / "src" / "app"
    shell_templates = [
        ("operational/code/typescript/app.routes.ts.j2", app_src_dir / "app.routes.ts"),
        ("operational/code/typescript/shell/app-shell.component.ts.j2",
         app_src_dir / "shell" / "app-shell.component.ts"),
        ("operational/code/typescript/shell/sidebar.component.ts.j2",
         app_src_dir / "shell" / "sidebar.component.ts"),
        ("operational/code/typescript/shell/topbar.component.ts.j2",
         app_src_dir / "shell" / "topbar.component.ts"),
    ]
    if ctx_data["ai"].get("hasAi"):
        shell_templates.append((
            "operational/code/typescript/shell/ai-panel.component.ts.j2",
            app_src_dir / "shell" / "ai-panel.component.ts",
        ))

    shell_rendered = 0
    for tmpl_rel, output_path in shell_templates:
        if render_jinja(workspace, tmpl_rel, jinja_ctx, output_path):
            shell_rendered += 1

    # D-331: do NOT pre-create libs/<lib>/src/ stubs here. The src/ tree is
    # produced by `nx generate @nx/angular:lib` at scaffold time; writing it
    # early leaves an orphaned directory that the generator would need to
    # overwrite or merge. The tsconfig.base.json paths (above) already point
    # at the correct future location — they don't require the files to exist.

    # D-290 + D-314: optional prototype analysis + vendoring.
    # Source resolution order:
    #   1. prototypePath (relative to target) — if already points to vendored copy.
    #   2. _extensions.frontend_reference.path (absolute, set by ingest_discovery) — external source.
    # When source is external (case 2), copy to frontend/design-reference/ and update context.
    prototype_path_raw = ctx_data["stack"]["frontend"].get("prototypePath", "")
    ext_fr_path = ctx_data.get("_extensions", {}).get("frontend_reference", {}).get("path", "")

    analysis_path: Path | None = None

    if prototype_path_raw:
        candidate = Path(prototype_path_raw)
        if not candidate.is_absolute():
            candidate = target / candidate
        if candidate.exists():
            analysis_path = candidate  # already vendored or local

    if analysis_path is None and ext_fr_path:
        ext_source = Path(ext_fr_path)
        if ext_source.exists() and ext_source.is_dir():
            # D-314: vendor the external prototype into frontend/design-reference/
            vendor_dst = target / "frontend" / "design-reference"
            if vendor_dst.exists():
                shutil.rmtree(vendor_dst)
            shutil.copytree(ext_source, vendor_dst)
            ctx_data["stack"]["frontend"]["prototypePath"] = "frontend/design-reference"
            file_count = len([f for f in vendor_dst.rglob("*") if f.is_file()])
            print(f"[P5] prototype vendored → frontend/design-reference/ ({file_count} files)")
            analysis_path = vendor_dst

    if analysis_path is not None:
        map_out = target / "docs" / "architecture" / "frontend" / "prototype-map.json"
        ws_analyzer = workspace / "scripts" / "fe-prototype-analyzer.py"
        if ws_analyzer.exists():
            result = subprocess.run(
                [sys.executable, str(ws_analyzer), "analyze",
                 "--prototype", str(analysis_path),
                 "--output", str(map_out)],
                capture_output=True, text=True,
            )
            if result.returncode == 0:
                print(f"[P5] prototype-map.json written → {map_out.relative_to(target)}")
            else:
                print(f"[P5] warning: fe-prototype-analyzer failed: {result.stderr.strip()}")

    mark_phase(target, ctx_data, "P5-frontend-skeleton", "done")
    libs_summary = f"{len(lib_names)} lib(s)" if lib_names else "libs/ empty"
    shell_summary = f"{shell_rendered} shell file(s)" if shell_rendered else "no shell templates"
    print(
        f"[P5] done — frontend/nx.json, tsconfig.base.json, package.json, "
        f"apps/{project_name}-web/ ({shell_summary}), {libs_summary}"
    )
    return 0


