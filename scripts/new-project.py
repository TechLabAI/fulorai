def cmd_knowledge_skeleton(args: argparse.Namespace) -> int:
    """Pk — Materialize the knowledge layer into the generated project (D-283).

    Mirrors docs-skeleton: reads context, copies/renders templates/knowledge/**
    into docs/knowledge/ in the target project. Post-processed per R2.
    Idempotent: re-runnable without side-effects.

    NOTE: templates/knowledge/ is produced by S13/S14 (PP v4). Until that
    stream is merged, this command materializes a stub directory.
    """
    target = args.target.resolve()
    workspace = find_workspace_root(args.workspace)
    ctx_data = load_context(target, args.context)

    knowledge_src = workspace / "templates" / "knowledge"
    if not knowledge_src.is_dir():
        stub_dir = target / "docs" / "knowledge"
        stub_dir.mkdir(parents=True, exist_ok=True)
        write_stub(
            stub_dir / "README.md",
            "Knowledge Layer",
            "knowledge/README.md",
        )
        mark_phase(target, ctx_data, "Pk-knowledge-skeleton", "done")
        print("[Pk] templates/knowledge/ not yet extracted (S13/S14 pending); stub written")
        return 0

    jinja_vars = build_jinja_context(ctx_data)
    from render import apply_arch_decisions
    apply_arch_decisions(workspace, jinja_vars)

    knowledge_dst = target / "docs" / "knowledge"
    knowledge_dst.mkdir(parents=True, exist_ok=True)

    # Internal directories: _includes/ (Jinja includes) and _meta/ (template-authoring
    # tools) are not materialized into the generated project — they are internal to
    # the knowledge layer's template system. Only charter/ and top-level templates
    # (knowledge-note, playbook) become output files.
    _SKIP_DIRS = {"_includes", "_meta"}

    rendered = stub = 0
    for src_file in sorted(knowledge_src.rglob("*")):
        if src_file.is_dir():
            continue
        rel = src_file.relative_to(knowledge_src)
        # Skip internal directories
        if any(part in _SKIP_DIRS for part in rel.parts[:-1] if part != rel.name):
            continue
        if rel.parts[0] in _SKIP_DIRS:
            continue
        if src_file.suffix == ".j2":
            dst = knowledge_dst / rel.parent / src_file.stem  # strip .j2
            dst.parent.mkdir(parents=True, exist_ok=True)
            template_rel = f"knowledge/{rel.as_posix()}"
            ok = render_jinja(workspace, template_rel, jinja_vars, dst)
            if ok:
                rendered += 1
            else:
                write_stub(dst, src_file.stem, template_rel)
                stub += 1
        else:
            dst = knowledge_dst / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src_file, dst)
            rendered += 1

    mark_phase(target, ctx_data, "Pk-knowledge-skeleton", "done")
    print(f"[Pk] done — {rendered} file(s) materialized, {stub} stub(s)")
    return 0


def cmd_integration_overlay(args: argparse.Namespace) -> int:
    """Pe — Copy/render an integration overlay into the generated project (D-283).

    Resolves templates/operational/integrations/<overlay>/ and copies it into
    integrations/<overlay>/ in the target. Idempotent.

    NOTE: the elastic-stack overlay is produced by S15 (PP v4). Until that
    stream is merged, this command materializes a stub directory.
    """
    overlay_name = getattr(args, "overlay", "elastic-stack")
    target = args.target.resolve()
    workspace = find_workspace_root(args.workspace)
    ctx_data = load_context(target, args.context)

    overlay_src = (
        workspace / "templates" / "operational" / "integrations" / overlay_name
    )
    if not overlay_src.is_dir():
        stub_dir = target / "integrations" / overlay_name
        stub_dir.mkdir(parents=True, exist_ok=True)
        write_stub(
            stub_dir / "README.md",
            f"{overlay_name} integration overlay",
            f"operational/integrations/{overlay_name}/README.md",
        )
        phase_id = f"Pe-integration-overlay:{overlay_name}"
        mark_phase(target, ctx_data, phase_id, "done")
        print(f"[Pe] overlay {overlay_name!r} not yet extracted (S15 pending); stub written")
        return 0

    jinja_vars = build_jinja_context(ctx_data)
    dst_root = target / "integrations" / overlay_name
    dst_root.mkdir(parents=True, exist_ok=True)

    rendered = stub = 0
    for src_file in sorted(overlay_src.rglob("*")):
        if src_file.is_dir():
            continue
        rel = src_file.relative_to(overlay_src)
        if src_file.suffix == ".j2":
            dst = dst_root / rel.parent / src_file.stem
            dst.parent.mkdir(parents=True, exist_ok=True)
            tpl_rel = f"operational/integrations/{overlay_name}/{rel.as_posix()}"
            ok = render_jinja(workspace, tpl_rel, jinja_vars, dst)
            rendered += 1 if ok else 0
            if not ok:
                write_stub(dst, src_file.stem, tpl_rel)
                stub += 1
        else:
            dst = dst_root / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src_file, dst)
            rendered += 1

    phase_id = f"Pe-integration-overlay:{overlay_name}"
    mark_phase(target, ctx_data, phase_id, "done")
    print(f"[Pe] overlay {overlay_name!r} done — {rendered} materialized, {stub} stub(s)")
    return 0


def cmd_phases(args: argparse.Namespace) -> int:
    """Print the resolved phase set for an archetype (D-280, ADR-003).

    Machine-readable with --json. Used by the /new-project orchestrator to avoid
    hardcoding the phase list per archetype.
    """
    workspace = find_workspace_root(args.workspace)
    archetype = getattr(args, "archetype", None) or "code-monorepo"
    manifest = load_segment_manifest(workspace, archetype)
    validate_manifest(manifest, workspace)
    phases = resolve_phase_set(manifest)

    if getattr(args, "json", False):
        print(json.dumps({"archetype": archetype, "phases": phases}))
    else:
        print(f"archetype: {archetype}")
        print(f"phases:    {' -> '.join(phases)}")
    return 0


def cmd_scan_archetypes(args: argparse.Namespace) -> int:
    """Print all available archetypes discovered from templates/segments/."""
    workspace = find_workspace_root(args.workspace)
    archetypes = scan_archetypes(workspace)
    if getattr(args, "json", False):
        print(json.dumps({"archetypes": archetypes}))
    else:
        for a in archetypes:
            manifest = load_segment_manifest(workspace, a)
            desc = manifest.get("description", "")
            print(f"  {a:<20} {desc}")
    return 0


