# ── Workspace + context resolution ────────────────────────────────────────────


def find_workspace_root(explicit: Path | None) -> Path:
    """Locate the techlab-architecture workspace.

    Order: --workspace > TECHLAB_ARCH_HOME > walk up from cwd > abort.
    """
    if explicit:
        if not _looks_like_workspace(explicit):
            sys.exit(f"error: --workspace {explicit} does not look like a techlab-architecture workspace")
        return explicit.resolve()

    env = os.environ.get("TECHLAB_ARCH_HOME")
    if env:
        p = Path(env)
        if not _looks_like_workspace(p):
            sys.exit(f"error: TECHLAB_ARCH_HOME={env} does not look like a workspace")
        return p.resolve()

    cwd = Path.cwd()
    for parent in [cwd, *cwd.parents]:
        if _looks_like_workspace(parent):
            return parent.resolve()

    sys.exit(
        "error: could not locate techlab-architecture workspace. "
        "Pass --workspace, set TECHLAB_ARCH_HOME, or run from inside the workspace."
    )


def _looks_like_workspace(p: Path) -> bool:
    """A workspace has scripts/new-project.py and templates/ directory."""
    return (p / "scripts" / "new-project.py").exists() and (p / "templates").is_dir()


def load_context(target: Path, override: Path | None) -> dict[str, Any]:
    """Load the project-context.json for the target project."""
    if override:
        path = override
    else:
        path = target / "project-context.json"
    if not path.exists():
        sys.exit(f"error: project-context.json not found at {path}")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        sys.exit(f"error: {path} is not valid JSON: {e}")


def save_context(target: Path, ctx: dict[str, Any]) -> None:
    """Save context with refreshed lastUpdatedAt."""
    ctx["lastUpdatedAt"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    path = target / "project-context.json"
    path.write_text(json.dumps(ctx, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def mark_phase(target: Path, ctx: dict[str, Any], phase_id: str, status: str) -> None:
    """Update setup.phases[<phase_id>].status."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    for phase in ctx.get("setup", {}).get("phases", []):
        if phase.get("id") == phase_id:
            if status == "in-progress" and "startedAt" not in phase:
                phase["startedAt"] = now
            if status == "done":
                phase["completedAt"] = now
                if "startedAt" not in phase:
                    phase["startedAt"] = now
            phase["status"] = status
            break
    save_context(target, ctx)


# ── Client registry helper (D-098) ────────────────────────────────────────────

import re as _re

_CLIENT_ID_RE = _re.compile(r"^[a-z0-9][a-z0-9-]*$")


def register_client(
    workspace: Path,
    target: Path,
    client_id: str,
    ctx: dict[str, Any],
    force: bool = False,
) -> Path:
    """Write ``<workspace>/clients/<client_id>.json`` so impact_analysis.py can
    discover this project (D-096 registry, D-098 auto-registration).

    `client_id` must be kebab-case (`[a-z0-9][a-z0-9-]*`). The file is refused
    when it already exists unless ``force=True`` — protects against typos that
    would silently overwrite a sibling registration.
    """
    if not _CLIENT_ID_RE.match(client_id):
        sys.exit(
            f"error: invalid --register-as value {client_id!r}: must match "
            f"{_CLIENT_ID_RE.pattern} (kebab-case, lowercase, starts with "
            f"alnum)"
        )

    clients_dir = workspace / "clients"
    clients_dir.mkdir(exist_ok=True)
    out = clients_dir / f"{client_id}.json"
    if out.exists() and not force:
        sys.exit(
            f"error: client registry already has {out.name}; "
            f"re-run with --force to overwrite"
        )

    project = ctx.get("project") or {}
    # Prefer a workspace-relative path; fall back to absolute when target lives
    # outside the workspace tree (the common case for real client projects).
    try:
        project_path_str = os.path.relpath(target, workspace).replace("\\", "/")
    except ValueError:
        project_path_str = str(target).replace("\\", "/")

    payload: dict[str, Any] = {
        "_schema_version": 1,
        "project": client_id,
        "project_path": project_path_str,
        "registered_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    repo = project.get("repo")
    if isinstance(repo, str) and repo:
        payload["repo"] = repo
    notes = project.get("description") or project.get("displayName")
    if isinstance(notes, str) and notes:
        payload["notes"] = notes

    out.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return out


