    frontend_dir.mkdir(exist_ok=True)

    project_name = ctx_data["project"]["name"]
    frontend = ctx_data["stack"]["frontend"]
    # npmScope in project-context.json is stored with the leading "@" (e.g. "@bosq");
    # strip it here since we re-add it when composing path keys (`@<scope>/<lib>`).
    npm_scope = (frontend["npmScope"] or "").lstrip("@")
    # D-082: consume project-context version. Strip a trailing "+" or "x" so
    # values like "18+" become a clean npm dep specifier (Angular ^18.0.0).
