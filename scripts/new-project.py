def filter_commands_for_audience(cmd_names: list[str], include_architect: bool) -> list[str]:
    """Filter command names by audience: dev-only (default) or dev+architect.

    A command is kept if it's in DEVELOPMENT_COMMANDS, or if it's in
    ARCHITECT_COMMANDS AND include_architect is True.

    Commands not in either set (e.g. helpers like next-phase) are always kept.
    """
    result = []
    for name in cmd_names:
        stem = name.replace(".md.j2", "").replace(".md", "")
        if stem in DEVELOPMENT_COMMANDS:
            result.append(name)
        elif stem in ARCHITECT_COMMANDS:
            if include_architect:
                result.append(name)
        else:
            # Helper/unclassified: keep by default
            result.append(name)
    return result



