"""new-project.py — Generator script invoked by /new-project command.

Materializes the 5 bootstrap phases of a new project (P0, P1, P2, P4, P5).
P3 (TechLab AI sync) is a separate script: sync-techlab-ai.py.
P6 (handoff) is just a message, handled by the /new-project command itself.

Phases:
    P0 bootstrap            -- repo skeleton, git init, .gitignore, README.md, tmp/
    P1 claude-folder        -- .claude/commands/ + settings.local.json + CLAUDE.md
    P2 docs-skeleton        -- docs/architecture/ tree per rigor level
    P4 backend-skeleton     -- backend/ Gradle root + scripts/ copy
    P5 frontend-skeleton    -- frontend/ Nx workspace (conditional)

Workspace resolution:
    1. --workspace flag (explicit path to techlab-architecture)
    2. TECHLAB_ARCH_HOME env var
    3. Walk up from cwd looking for templates/ + scripts/new-project.py
    4. Abort

Stub strategy (Q1=b):
    When a template is missing in templates/, generate a placeholder file
    with a TODO header pointing to which Lote will provide it. The project
    can be regenerated/refreshed later by running phase commands again.

Usage:
    python new-project.py bootstrap --target ~/dev/bosq --context /path/to/project-context.json
    python new-project.py claude-folder --target ~/dev/bosq
    python new-project.py docs-skeleton --target ~/dev/bosq --rigor complete-bosq
    python new-project.py backend-skeleton --target ~/dev/bosq
    python new-project.py frontend-skeleton --target ~/dev/bosq

Each subcommand reads project-context.json from <target>/project-context.json
(unless --context overrides). After each phase, the phase status in
setup.phases is updated to "done" (or "blocked" on failure).
"""
