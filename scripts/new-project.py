def _load_segment_schema(workspace: Path) -> dict[str, Any]:
    path = (
        workspace / "docs" / "specs" / "segments-mechanism"
        / "contracts" / "segment.schema.json"
    )
    if not path.exists():
        sys.exit(f"error: segment schema not found: {path}")
    return json.loads(path.read_text(encoding="utf-8"))


def scan_archetypes(workspace: Path) -> list[str]:
    """Return all known archetype names (built-in + discovered from templates/segments/)."""
    known: list[str] = ["code-monorepo"]
    seg_dir = workspace / "templates" / "segments"
    if not seg_dir.is_dir():
        return known
    for entry in sorted(seg_dir.iterdir()):
        if not (entry.is_dir() and (entry / "segment.json").exists()):
            continue
        try:
            m = json.loads((entry / "segment.json").read_text(encoding="utf-8"))
            a = m.get("archetype")
            if a and a not in known:
                known.append(a)
        except (json.JSONDecodeError, KeyError):
            pass
    return known


def load_segment_manifest(workspace: Path, archetype: str) -> dict[str, Any]:
    """Load the segment manifest for archetype (D-278).

    Resolution: templates/segments/<archetype>/segment.json > built-in default.
    Does NOT validate — call validate_manifest() after.
    Exits 2 on unknown archetype or malformed JSON.
    """
    if archetype == "code-monorepo":
        disk = workspace / "templates" / "segments" / "code-monorepo" / "segment.json"
        if disk.exists():
            try:
                return json.loads(disk.read_text(encoding="utf-8"))
            except json.JSONDecodeError as e:
                sys.exit(f"error: invalid manifest JSON (code-monorepo): {e}")
        return dict(_CODE_MONOREPO_DEFAULT)

    path = workspace / "templates" / "segments" / archetype / "segment.json"
    if not path.exists():
        valid = ", ".join(scan_archetypes(workspace))
        sys.exit(f"error: unknown archetype {archetype!r}. Valid: {valid}")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        sys.exit(f"error: invalid manifest JSON ({archetype}): {e}")


def validate_manifest(manifest: dict[str, Any], workspace: Path) -> None:
    """Validate manifest against segment.schema.json. Exits 2 on violation (D-278, R3)."""
    try:
        import jsonschema as _js  # type: ignore
    except ImportError:
        print("error: jsonschema required for manifest validation (pip install jsonschema)",
              file=sys.stderr)
        sys.exit(2)
    schema = _load_segment_schema(workspace)
    try:
        _js.validate(manifest, schema)
    except _js.ValidationError as e:
        print(f"error: manifest schema violation: {e.json_path} -- {e.message}",
              file=sys.stderr)
        sys.exit(2)

    layers = manifest.get("layers", {})
    inc = set(layers.get("include", []))
    exc = set(layers.get("exclude", []))
    if inc & exc:
        print(
            f"error: layer(s) both included and excluded: "
            f"{', '.join(sorted(inc & exc))}",
            file=sys.stderr,
        )
        sys.exit(2)
    for seed in manifest.get("seeds", []):
        dest = seed.get("dest", "")
        if dest.startswith("/") or ".." in dest.split("/"):
            print(f"error: bad seed mapping dest {dest!r}", file=sys.stderr)
            sys.exit(2)


def resolve_phase_set(manifest: dict[str, Any]) -> list[str]:
    """Return ordered phase ids for the manifest (D-279). Pure function, no I/O."""
    layers: set[str] = {"operational"}
    spec = manifest.get("layers", {})
    layers |= set(spec.get("include", []))
    layers -= set(spec.get("exclude", []))
    phases: list[str] = []
    for layer in CANONICAL_LAYER_ORDER:
        if layer in layers:
            phases.extend(LAYER_PHASES[layer])
    return phases


def resolve_archetype(args: argparse.Namespace, ctx: dict[str, Any] | None = None) -> str:
    """Precedence: --archetype flag > context.project.archetype > 'code-monorepo' (D-280)."""
    flag = getattr(args, "archetype", None)
    if flag:
        return flag
    if ctx:
        return (ctx.get("project") or {}).get("archetype") or "code-monorepo"
    return "code-monorepo"


def _apply_seeds(workspace: Path, manifest: dict[str, Any], target: Path) -> int:
    """Copy seed files from the segment dir into the target project (D-278, Fase C).

    Seeds are plain content files (not Jinja); copied verbatim and R2-normalized.
    Existing destinations are NOT overwritten -- user edits survive a re-run.
    Returns the number of files copied.
    """
    import re as _re

    seeds = manifest.get("seeds", [])
    if not seeds:
        return 0

    seg_name = manifest.get("name", "")
    seg_dir = workspace / "templates" / "segments" / seg_name
    n = 0

    for seed in seeds:
        src_rel: str = seed.get("src", "")
        dest_rel: str = seed.get("dest", "")
        if not src_rel or not dest_rel:
            continue
        src_path = seg_dir / src_rel
        dst_path = target / dest_rel

        if not src_path.exists():
            print(f"[seeds] warning: seed src not found (skipped): {src_path}",
                  file=sys.stderr)
            continue

        if src_path.is_dir():
            for src_file in sorted(src_path.rglob("*")):
                if src_file.is_dir():
                    continue
                rel = src_file.relative_to(src_path)
                dst_file = dst_path / rel
                if dst_file.exists():
                    continue  # preserve user edits
                dst_file.parent.mkdir(parents=True, exist_ok=True)
                text = src_file.read_text(encoding="utf-8")
                text = _re.sub(r"\n{3,}", "\n\n", text)
                if not text.endswith("\n"):
                    text += "\n"
                dst_file.write_text(text, encoding="utf-8")
                n += 1
        else:
            if dst_path.exists():
                continue  # preserve user edits
            dst_path.parent.mkdir(parents=True, exist_ok=True)
            text = src_path.read_text(encoding="utf-8")
            text = _re.sub(r"\n{3,}", "\n\n", text)
            if not text.endswith("\n"):
                text += "\n"
            dst_path.write_text(text, encoding="utf-8")
            n += 1

    return n


